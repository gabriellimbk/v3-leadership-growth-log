-- Preserve the app's current access behaviour while keeping non-submission
-- writes limited to authenticated Supabase teacher sessions.
DROP POLICY IF EXISTS "v3_records_read_all"
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG";
DROP POLICY IF EXISTS "v3_records_insert"
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG";
DROP POLICY IF EXISTS "v3_records_update"
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG";
DROP POLICY IF EXISTS "v3_records_delete"
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG";

CREATE POLICY "v3_records_read_all"
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG"
  FOR SELECT USING (true);

CREATE POLICY "v3_records_insert"
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG"
  FOR INSERT WITH CHECK (
    record_type = 'submission' OR auth.role() = 'authenticated'
  );

CREATE POLICY "v3_records_update"
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG"
  FOR UPDATE USING (
    record_type = 'submission' OR auth.role() = 'authenticated'
  ) WITH CHECK (
    record_type = 'submission' OR auth.role() = 'authenticated'
  );

CREATE POLICY "v3_records_delete"
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG"
  FOR DELETE USING (
    record_type = 'submission' OR auth.role() = 'authenticated'
  );

