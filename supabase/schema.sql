-- Run this in the Supabase SQL Editor for the shared project.
-- All v3 application records are stored in this one table. Every existing
-- table in the shared project is left untouched.

CREATE TABLE IF NOT EXISTS public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG" (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_type TEXT NOT NULL,
  record_key TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Student submission fields.
  student_uid TEXT,
  student_email TEXT,
  student_name TEXT,
  teacher_id TEXT,
  answers JSONB,
  comments JSONB,
  status TEXT,

  -- Form configuration field.
  config JSONB,

  -- Teacher directory fields.
  name TEXT,
  email TEXT,

  CONSTRAINT v3_leadership_growth_log_record_type_check
    CHECK (record_type IN ('submission', 'form_config', 'teacher')),
  CONSTRAINT v3_leadership_growth_log_status_check
    CHECK (status IS NULL OR status IN ('draft', 'submitted', 'reviewed')),
  CONSTRAINT v3_leadership_growth_log_record_shape_check
    CHECK (
      (record_type = 'submission' AND student_uid IS NOT NULL AND student_name IS NOT NULL
        AND teacher_id IS NOT NULL AND answers IS NOT NULL AND comments IS NOT NULL
        AND status IS NOT NULL)
      OR (record_type = 'form_config' AND record_key IS NOT NULL AND config IS NOT NULL)
      OR (record_type = 'teacher' AND name IS NOT NULL AND email IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS v3_leadership_growth_log_record_key_idx
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG" (record_key);

CREATE UNIQUE INDEX IF NOT EXISTS v3_leadership_growth_log_student_uid_idx
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG" (student_uid);

CREATE UNIQUE INDEX IF NOT EXISTS v3_leadership_growth_log_teacher_email_idx
  ON public."V3-LEADERSHIP-PROGRAMME-GROWTH-LOG" (LOWER(email))
  WHERE record_type = 'teacher';

